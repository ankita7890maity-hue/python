'''Write a program to take how many times alarm was snoozed from user. 
If more than 3, print "Alarm bhi thak gaya hoga bhai 😩",
else "Discipline OP 🔔".'''

snoozed = int(input("Alarm kitni bar snooze kiya? "))
if snoozed > 3:
    print("alarm bhi thak gya hoga bhai")
else:
    print("Discipline OP")
    

