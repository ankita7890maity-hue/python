'''Write a program to take time of arrival at college from user.
If after 9, print "Late ho gaya bhai! Security guard abhi attitude dikhayega 😬", 
else "Time se aa gaya! Sahi hai 👌".'''

time = int(input("kitne baje college poche? "))
if time > 9:
    print("Late ho gaya bhai! Security guard abhi attitude dikhayega 😬")
else:
    print("Time se aa gaya! Sahi hai 👌")